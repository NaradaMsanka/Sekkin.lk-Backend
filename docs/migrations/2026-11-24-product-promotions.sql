-- Additive migration. Run against the intended database before deploying this backend.
-- Existing order amounts and old promotional decisions are left unchanged.
CREATE TABLE IF NOT EXISTS promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    percentage NUMERIC(5,2) NOT NULL CHECK (percentage > 0 AND percentage <= 100),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_promotions_code UNIQUE (code)
);
CREATE TABLE IF NOT EXISTS promotion_products (
    promotion_id BIGINT NOT NULL REFERENCES promotions(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL,
    CONSTRAINT uk_promotion_product UNIQUE (promotion_id, product_id)
);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_percentage NUMERIC(5,2);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS coupon_discount DOUBLE PRECISION;
